"""Build payload.js: everything the converter page adds to the game, and nothing of the game.

usage: python3 tools/mkpayload.py <WOLF.g1a> build/shim.elf build/shim.bin

The CG50 OS maps an add-in's code at 0x00300000, the same address the fx-9860 OS uses, so the
game's code goes unchanged to 0x00300200 (right after the 0x200-byte g1a header it had):
  0x00300000  a jump to the shim's start (where the g1a header was)
  0x00300200  the game, patched: every fx-9860 syscall stub's 0x80010070 points to the shim's
              syscall gate, and three hardware routines jump to hooks
  0x00320000  the shim (shim/shim.ld)

payload.js holds a complete .g3a (fxgxa) with zeros where the game goes, and the patches as
(offset in the .g1a, bytes). The page fills in the user's copy of the game, applies the patches
and recomputes the .g3a checksum. Also written: build/reference.g3a, the same add-in built
directly with fxgxa, which the converter's output must match byte for byte (make check).
"""
import base64, hashlib, json, os, struct, subprocess, sys

BASE = 0x00300000
SHIM = 0x00320000
FX_SYSCALL = 0x80010070
STUB = bytes.fromhex('d201d002422b0009')  # mov.l @(1,pc),r2; mov.l @(2,pc),r0; jmp @r2; nop

# Kelli's "Last Wolfenstein 3D", SH4 version (Planete Casio programme 1967, file 2)
GAME_SHA1 = 'f84c88c23f5d4d32829d5b8adc3d3191e6978377'
# The two other files of that page, to tell the user which one to take instead
OTHER_SHA1 = {
    '617da6a1b73c8f6f9be667a7b27d320a8346a7f4': 'the SH3 version (file 1)',
    '2b716ff0f28f9fe176f45013b930b2071a2ee1bc': 'the Graph 35+E II version (file 3)',
}
# Routines to replace: (address, shim symbol, their first 12 bytes)
HOOKS = [
    (0x309EF8, '_hook_lcd_push', '2fc62fb62fa62f962f866a43'),     # 1 KB VRAM -> LCD at 0xB4000000
    (0x309F68, '_hook_exit', 'd001402b00090000a0000000'),         # jmp 0xA0000000 (quit)
    (0x30829C, '_hook_rtc_seconds', 'e4ff441874c0e01c004ce6fc'),  # SH3 RTC seconds
]
G3A = dict(name='Wolf3D', internal='@WOLF3D', version='01.00.0000', date='2026.1010.0000')


def symbols(elf):
    out = subprocess.run(['sh-elf-nm', elf], check=True, capture_output=True, text=True).stdout
    return {p[2]: int(p[0], 16) for p in (l.split() for l in out.splitlines()) if len(p) == 3}


def jump_to(addr, target):
    """mov.l @(1,pc),r1; jmp @r1; nop; [nop]; .long target -- 12 bytes at a 4-aligned address,
    10 at a 2-aligned one. r1 is scratch at a routine's entry under the SHC convention."""
    code = bytes.fromhex('d101412b0009')
    if addr % 4 == 0:
        code += bytes.fromhex('0009')
    return code + struct.pack('>I', target)


def fxgxa(image, out):
    raw = out + '.bin'
    open(raw, 'wb').write(image)
    subprocess.run(['fxgxa', '--g3a', '-n', G3A['name'], '--internal=' + G3A['internal'],
                    '--version=' + G3A['version'], '--date=' + G3A['date'],
                    '--icon-uns=icon/icon-uns.png', '--icon-sel=icon/icon-sel.png',
                    raw, '-o', out], check=True)
    os.remove(raw)
    return open(out, 'rb').read()


def main(g1a_path, elf, shim_bin):
    g1a = open(g1a_path, 'rb').read()
    if hashlib.sha1(g1a).hexdigest() != GAME_SHA1:
        sys.exit(f'{g1a_path}: not the SH4 version of the game')
    syms = symbols(elf)

    patches = []
    for off in range(0x200, len(g1a) - 12, 2):
        if g1a[off:off + 8] == STUB and struct.unpack('>I', g1a[off + 8:off + 12])[0] == FX_SYSCALL:
            patches.append((off + 8, struct.pack('>I', syms['_fx_syscall'])))
    for addr, sym, expect in HOOKS:
        off = addr - BASE
        if g1a[off:off + 12].hex() != expect:
            sys.exit(f'{addr:#x}: expected {expect}, found {g1a[off:off + 12].hex()}')
        patches.append((off, jump_to(addr, syms[sym])))

    image = bytearray(SHIM - BASE)
    image[0:12] = jump_to(BASE, syms['_shim_start'])
    image += open(shim_bin, 'rb').read()
    template = fxgxa(bytes(image), 'build/template.g3a')

    full = bytearray(image)
    full[0x200:len(g1a)] = g1a[0x200:]
    for off, data in patches:
        full[off:off + len(data)] = data
    fxgxa(bytes(full), 'build/reference.g3a')

    payload = {
        'sha1': GAME_SHA1,
        'size': len(g1a),
        'others': OTHER_SHA1,
        'code': 0x7000,
        'template': base64.b64encode(template).decode(),
        'patches': [[off, data.hex()] for off, data in patches],
    }
    with open('payload.js', 'w') as f:
        f.write('// Generated by tools/mkpayload.py: the shim and the .g3a around it, no game data.\n')
        f.write('var WOLF_PAYLOAD = ' + json.dumps(payload) + ';\n')
    print(f'payload.js: {len(patches)} patches, template {len(template)} bytes')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
